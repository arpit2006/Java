public class Operators {
    public static void main(String[] args) {
        //Four Type of Operator
        //Arithmetic Operator eg. +
        //Assignment Operator eg. =
        // Comparison Operator eg.& ==
        //Bitwise Operator eg. |
        int a = 4;
        int b = a + 6; // Add( = is assingenment operator)

        System.out.print("Sum is..: ");
        System.out.println(b);

        float num1 =  4.2f;
        float num2 = 5.2f;

        float rem = num1 % num2;

        System.out.print("Remainder is..: ");
        System.out.print(rem);
    }
}
